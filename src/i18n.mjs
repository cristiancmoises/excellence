export function resolveLanguage(search = "") {
  return new URLSearchParams(search).get("lang") === "pt-BR" ? "pt-BR" : "en";
}

export function languageUrl(href, language) {
  const url = new URL(href);
  url.searchParams.set("lang", language === "pt-BR" ? "pt-BR" : "en");
  return url.pathname + url.search + url.hash;
}

export function translate(key, language = "en", values = {}) {
  const text = language === "pt-BR" ? key : messages[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
}
